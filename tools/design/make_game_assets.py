# Game assets: every static layer of the desk, drawn by the design scripts.
# Run from tools/design:  python3 make_game_assets.py  (then rasterize, see docs/design/README.md)
#   desk.svg         the wide desk, for any screen shape (viewBox -800 -400 3040 1700)
#   globe-base.svg     the globe's turned wooden stand and shadow
#   globe-terrain.svg  the world inside the globe (the Watch's forest drawn small at the village)
#   globe-glass.svg    the sphere's glass: rim, candle light, reflections (kept as SVG)
#   watch.svg          the forest under the reading glass
#   watch-frame.svg    the reading glass: rim, glass, handle, shadows (drawn above the notes)
#   hearth.svg         the village under the big loupe
#   hearth-frame.svg   the loupe's rim, glass and jointed arm (drawn above the notes)
#   ../../js/render/defs.js and ../../js/data/hotspots.js
import os, json, random, math
import desk as D, scene5 as S5, make4 as M4, hearth3 as H3, hearth4 as H4, hearth6 as H5, globe6 as G6
W,H=1440,900
OUT=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..','assets')
JS=os.path.join(os.path.dirname(os.path.abspath(__file__)),'..','..','js')
os.makedirs(OUT,exist_ok=True)
DEFS=S5.defs().replace('</defs>',G6.STAND_DEFS+G6.LENS_DEFS+H5.DEFS+'</defs>')
def svg(body,vb=f'0 0 {W} {H}',w=W,h=H,tex=False):
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vb}" width="{w}" height="{h}">'+DEFS+body+(f'<rect width="{W}" height="{H}" filter="url(#tex)"/>' if tex else '')+'</svg>'
def write(name,text): open(os.path.join(OUT,name),'w').write(text)

# the wide desk
def desk_wide():
    x0,y0,x1,y1=-800,-400,2240,1300
    r=random.Random(2)
    o=f'<radialGradient id="roomw" gradientUnits="userSpaceOnUse" cx="1360" cy="60" r="2200"><stop offset="0" stop-color="#4a2e22"/><stop offset=".45" stop-color="#2a1a16"/><stop offset="1" stop-color="#120a0b"/></radialGradient>'
    o+=f'<rect x="{x0}" y="{y0}" width="{x1-x0}" height="{y1-y0}" fill="url(#roomw)"/>'
    for i,x in enumerate(range(x0,x1,190)):
        o+=f'<rect x="{x}" y="{y0}" width="190" height="{y1-y0}" fill="{["#5a3322","#4e2c1e","#55301f"][i%3]}" opacity=".35"/><path d="M{x} {y0} V{y1}" stroke="#120806" stroke-width="3" opacity=".7"/>'
        for k in range(10):
            gx=x+r.uniform(10,180); o+=f'<path d="M{gx:.0f} {y0} C{gx+r.uniform(-30,30):.0f} {y0+500} {gx+r.uniform(-30,30):.0f} {y0+1100} {gx+r.uniform(-20,20):.0f} {y1}" stroke="#1a0c08" stroke-width="{r.uniform(.6,1.6):.1f}" fill="none" opacity=".35"/>'
        if i%3==1: o+=f'<path d="M{x} {y0+r.uniform(200,1400):.0f} h190" stroke="#120806" stroke-width="2.5" opacity=".6"/>'
    o+=f'<circle cx="1360" cy="60" r="620" fill="url(#candle)"/>'
    o+=f'<g transform="translate(1368 64)"><circle r="54" fill="url(#brass)" opacity=".9"/><circle r="44" fill="#6e4a1c" opacity=".5"/><circle r="30" fill="#efe1c6" stroke="#b39b78" stroke-width="2"/><circle r="5" fill="#2a1a12"/><path d="M0 0 q-7 -16 0 -30 q7 14 0 30z" fill="#ffd27a"/><circle r="70" fill="url(#warm)"/></g>'
    for lx,ly,rot,c,s in [(150,520,30,'#b4492c',3.0),(1010,860,-20,'#c98a2e',2.6),(230,880,70,'#8a3550',2.2),(1180,520,10,'#a8642a',2.4),(-260,300,40,'#c98a2e',2.6),(1720,760,-50,'#b4492c',2.8),(-120,980,10,'#6f3b5e',2.2),(1900,180,80,'#a8642a',2.4)]:
        o+=f'<use href="#leaf" x="-10" y="-5" width="20" height="10" fill="{c}" transform="translate({lx} {ly}) rotate({rot}) scale({s})" filter="url(#lift)"/>'
    return o
write('desk.svg',svg(desk_wide()+f'<rect x="-800" y="-400" width="3040" height="1700" filter="url(#tex)"/>',vb='-800 -400 3040 1700',w=3040,h=1700))
# the globe: stand (under everything), terrain (also magnified inside the lenses), glass
write('globe-base.svg',svg(G6.stand()))
LX,LY,LR=630,410,350
wm,_=S5.watch(10.4,LX,LY,LR,game=True)
write('globe-terrain.svg',svg(G6.terrain(2.95,miniature=None),vb='290 74 700 700',w=1050,h=1050))
write('globe-glass.svg',svg(G6.sphere_glass()))
open(os.path.join(JS,'data','places-art.js'),'w').write('// Each place\'s landmark in the globe, shown once it is discovered. Generated by tools/design/make_game_assets.py.\nexport const MARKERS = %s;\n' % json.dumps(G6.markers()))
# the reading glass: the forest under it, and its frame (drawn above the notes)
write('watch.svg',svg(wm,vb='280 60 700 700',w=700,h=700))
write('watch-frame.svg',svg(G6.lens_frame(LX,LY,LR,18,135,250),vb='0 0 1440 1000',w=1440,h=1000))
# the loupe over the village, and its frame and arm
CX,CY,RX,RY=636,430,400,374
# the village, in layers: ground, each building in three stages, trees in front
write('hearth-base.svg',svg(H5.base(),vb='236 56 800 748',w=800,h=748))
write('hearth-front.svg',svg(H5.front(),vb='236 56 800 748',w=800,h=748))
for st in range(3): write(f'walls-{st}.svg',svg(H5.walls(st),vb='236 56 800 748',w=800,h=748))
sprites={}; hot={}
for bid in H5.BOX:
    X,Y,(bx,by,bw,bh)=H5.sprite_box(bid)
    for st in range(3): write(f'b-{bid}-{st}.svg',svg(H5.building(bid,st,X,Y),vb=f'{bx:.1f} {by:.1f} {bw} {bh}',w=bw,h=bh))
    sprites[bid]=[round(bx,1),round(by,1),bw,bh]
    hw,up,_=H5.BOX[bid]; hot[bid]=[[round(X,1),round(Y,1),round(hw*.75),round(up*.85)]]
gx,gy=H5.P(H5.CX,H5.G,0,3.2); hot['walls']=[[round(gx,1),round(gy,1),40,70]]
feet={k:[round(v,1) for v in H5.P(H5.CX,H5.G,*xz)] for k,xz in H5.SPOTS.items()}
write('hearth-frame.svg',svg(G6.loupe_frame(CX,CY,RX,RY),vb='0 -360 1440 1260',w=1440,h=1260))
vill=[H5.villager_svg(c) for c in H5.VILLAGER_COLORS]
open(os.path.join(JS,'data','hotspots.js'),'w').write('// The Hearth view, in screen units of the 1440x900 desk. Generated by tools/design/make_game_assets.py.\n// HOTSPOTS: [x, y of a building\'s foot, half width, height]. SPRITES: [x, y, width, height] of\n// each building\'s images (assets/b-<id>-<stage>.webp). FEET: where each building stands.\nexport const HEARTH = { cx: %d, cy: %d, rx: %d, ry: %d };\nexport const HOTSPOTS = %s;\nexport const SPRITES = %s;\nexport const FEET = %s;\nexport const VILLAGERS = %s;\n' % (CX,CY,RX,RY,json.dumps(hot),json.dumps(sprites),json.dumps(feet),json.dumps(vill)))
open(os.path.join(JS,'render','defs.js'),'w').write('// Gradients, filters and creature symbols for the live SVG layer.\n// Generated by tools/design/make_game_assets.py from the design scripts.\nexport const DEFS = '+repr(DEFS).replace("\\n","")+';\n')
print('ok', list(hot))
