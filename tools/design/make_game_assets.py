# Game assets for the Watch view: the static artwork under and over the live layer.
# Run from tools/design:  python3 make_game_assets.py
import os, desk as D, scene5 as S5, make4 as M4, cozy
W,H=1440,900
OUT=os.path.join(os.path.dirname(__file__),'..','..','assets')
os.makedirs(OUT,exist_ok=True)
LX,LY,LR=630,410,350
def svg(body,tex=True): return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}">'+S5.defs()+body+(f'<rect width="{W}" height="{H}" filter="url(#tex)"/>' if tex else '')+'</svg>'
wm,_=S5.watch(10.4,LX,LY,LR,game=True)
base=D.desk()+S5.globe(dim=.35,blur=True)+D.lens_shadow(LX,LY,LR,18)+D.handle(LX,LY,LR,135,240)+wm
glass=D.lens(LX,LY,LR,ring=18)+M4.vign()
open(os.path.join(OUT,'watch-base.svg'),'w').write(svg(base))
open(os.path.join(OUT,'watch-glass.svg'),'w').write(svg(glass,tex=False))
# shared symbols and gradients for the live layer
defs=S5.defs()
open(os.path.join(OUT,'..','js','render','defs.js'),'w').write('// Gradients, filters and creature symbols for the live SVG layer.\n// Generated by tools/design/make_game_assets.py from the design scripts.\nexport const DEFS = '+repr(defs).replace("\\n","")+';\n')
print('ok')
